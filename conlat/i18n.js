let currentLang = 'es';

function t(key) {
  return CONLAT_I18N[currentLang][key] ?? CONLAT_I18N.es[key] ?? key;
}

function applyLang(lang) {
  currentLang = lang === 'en' ? 'en' : 'es';
  document.documentElement.lang = currentLang === 'en' ? 'en' : 'es-AR';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    el.alt = t(el.dataset.i18nAlt);
  });
  document.querySelectorAll('[data-i18n-wa]').forEach(el => {
    el.href = 'https://wa.me/5491154932199?text=' + encodeURIComponent(t(el.dataset.i18nWa));
  });

  document.title = t('meta.title');
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.content = t('meta.description');

  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
    btn.setAttribute('aria-pressed', btn.dataset.lang === currentLang ? 'true' : 'false');
  });

  updateCompareLabels();
}

function updateCompareLabels() {
  const table = document.querySelector('.compare-table');
  if (!table) return;
  const heads = [...table.querySelectorAll('thead th')].map(h => h.textContent.trim());
  table.querySelectorAll('tbody tr').forEach(tr => {
    tr.querySelectorAll('td').forEach((td, i) => {
      if (i > 0) td.setAttribute('data-label', heads[i]);
    });
  });
}

function initLangSwitch() {
  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });
  applyLang('es');
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initLangSwitch);
} else {
  initLangSwitch();
}
